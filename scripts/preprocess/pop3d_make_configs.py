#!/usr/bin/env python3
"""Generate the Lightning Pose and pipeline configs for 3d-pop_s (SLP3D joint crops).

Built *from* the r24m generator's templates so every training, model, loss and
schedule setting is literally the same text as config_r24m_s.yaml /
pipeline_r24m_s.yaml. Only dataset-specific fields are substituted, and each
substitution must hit exactly once or this script fails.

Dataset-specific choices:
  - views Cam1..Cam4, 9 keypoints, 18 bird tags as animal_names (2 or 5 per frame)
  - n_hand_labels = 478 rows: ALL in-distribution rows not held out for
    validation. 500 rows in 175 time-point groups at train_prob 0.95 /
    val_prob 0.05, seed 0, grouped split -> 478 train / 22 val. Same rule as
    r24m_s (496 = all of its train split). Re-measure if the data changes.
  - intermediate_results_dir crop_2.0: shipped crops are 2.0 x keypoint extent
    (r24m_s used 1.4, two-mouse_s 1.3).

Usage::

    python scripts/preprocess/pop3d_make_configs.py --seeds 0
"""
from __future__ import annotations

import argparse
from pathlib import Path

import r24m_make_configs as base

NAME = "3d-pop_s"
VIEWS = ["Cam1", "Cam2", "Cam3", "Cam4"]
KEYPOINTS = ["beak", "nose", "leftEye", "rightEye", "leftShoulder", "rightShoulder",
             "topKeel", "bottomKeel", "tail"]
ANIMALS = ["id47", "id54", "id382", "id389", "id391", "id452", "id473", "id475", "id483",
           "id484", "id485", "id486", "id487", "id497", "id705", "id706", "id707", "id708"]
TRAIN_ROWS = 478
INTERMEDIATE = "crop_2.0"

# From median 3D inter-keypoint distances (mm): head cluster beak-nose-eyes
# (19-21 mm), shoulders -> topKeel (47-53), topKeel -> bottomKeel (99),
# bottomKeel -> tail (84). Like the source dataset_info, no head-body edge.
# Only used for visualisation.
SKELETON = [
    ("beak", "nose"), ("nose", "leftEye"), ("nose", "rightEye"), ("leftEye", "rightEye"),
    ("leftShoulder", "rightShoulder"),
    ("leftShoulder", "topKeel"), ("rightShoulder", "topKeel"),
    ("topKeel", "bottomKeel"), ("bottomKeel", "tail"),
]
COLORS = {
    "beak-nose": "red", "nose-leftEye": "red", "nose-rightEye": "red",
    "leftEye-rightEye": "red",
    "leftShoulder-rightShoulder": "dodgerblue",
    "leftShoulder-topKeel": "dodgerblue", "rightShoulder-topKeel": "dodgerblue",
    "topKeel-bottomKeel": "darkred", "bottomKeel-tail": "mediumseagreen",
}


def sub(text: str, old: str, new: str) -> str:
    n = text.count(old)
    if n != 1:
        raise SystemExit(f"expected exactly one {old!r} in template, found {n}")
    return text.replace(old, new)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--config-dir", type=Path, default=base.CONFIG_DIR)
    p.add_argument("--seeds", type=int, nargs="+", default=[0])
    args = p.parse_args()

    # the template functions read these module globals at call time
    base.VIEWS, base.KEYPOINTS = VIEWS, KEYPOINTS
    base.SKELETON, base.SKELETON_COLORS = SKELETON, COLORS

    cfg = base.make_config(NAME, "joint", True)
    cfg = sub(cfg, "animal_names:\n    - an1\n    - an2\n",
              "animal_names:\n" + base.yaml_list(ANIMALS) + "\n")
    cfg = sub(cfg, "One row per (frame, rat)", "One row per (time point, pigeon)")
    cfg = sub(cfg, "keeps both rats of a frame", "keeps all birds (2 or 5) of a time point")
    cfg = sub(cfg, "Generated by scripts/preprocess/r24m_make_configs.py",
              "Generated by scripts/preprocess/pop3d_make_configs.py")

    pipe = base.make_pipeline(NAME, "joint", True, args.seeds)
    pipe = sub(pipe, f"intermediate_results_dir: crop_1.4",
               f"intermediate_results_dir: {INTERMEDIATE}")
    pipe = sub(pipe, f"    - {base.FRAME_BUDGET * 2}\n", f"    - {TRAIN_ROWS}\n")
    start = pipe.index("  # training.train_frames counts ROWS.")
    end = pipe.index("  n_hand_labels:")
    pipe = pipe[:start] + (
        "  # training.train_frames counts ROWS (one per bird per time point; 2 or 5\n"
        f"  # birds each). {TRAIN_ROWS} = every in-distribution row not held out for\n"
        "  # validation (grouped split, seed 0: 478 train / 22 val of 500), the same\n"
        "  # 'all available' rule used for the earlier SLP3D runs.\n"
    ) + pipe[end:]
    pipe = sub(pipe, "Generated by scripts/preprocess/r24m_make_configs.py",
               "Generated by scripts/preprocess/pop3d_make_configs.py")

    for text, kind in ((cfg, "config"), (pipe, "pipeline")):
        if "an1" in text or "r24m" in text or "rat" in text.split():
            bad = [l for l in text.splitlines() if "an1" in l or "r24m" in l or "rat" in l.split()]
            raise SystemExit(f"{kind}: r24m-specific text leaked into the 3d-pop config: {bad}")
    (args.config_dir / f"config_{NAME}.yaml").write_text(cfg)
    (args.config_dir / f"pipeline_{NAME}.yaml").write_text(pipe)
    print(f"wrote config_{NAME}.yaml and pipeline_{NAME}.yaml")


if __name__ == "__main__":
    main()
